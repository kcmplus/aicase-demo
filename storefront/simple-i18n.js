const escapePattern=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const compiled=patterns.map(([source,target])=>({regex:new RegExp('^'+source.split(/(\{\d+\})/).map(part=>/^\{\d+\}$/.test(part)?'(.+?)':escapePattern(part)).join('')+'$'),target}));
function translate(body,depth=0){
 if(depth>4||!body)return body;
 if(exact.has(body))return exact.get(body);
 for(const {regex,target} of compiled){const m=body.match(regex);if(m)return target.replace(/\{(\d+)\}/g,(_,i)=>translate(m[Number(i)+1],depth+1));}
 if(body.includes(' · '))return body.split(' · ').map(part=>translate(part,depth+1)).join(' · ');
 const decorated=body.match(/^([←✓◌✦]\s*)?(.+?)(\s*[→↗−+])?$/);
 if(decorated&&(decorated[1]||decorated[3]))return (decorated[1]||'')+translate(decorated[2],depth+1)+(decorated[3]||'');
 if(body.includes('. '))return body.split(/(?<=\.)\s+/).map(part=>translate(part,depth+1)).join(' ');
 if(body.endsWith('.')){const part=translate(body.slice(0,-1),depth+1);if(part!==body.slice(0,-1))return part+(part.endsWith('。')?'':'。');}
 return body;
}
